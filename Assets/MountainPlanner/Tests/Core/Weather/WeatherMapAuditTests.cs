        [Test]
        public void TheCanopySlowsTheWind()
        {
            var t = RoughTerrain(out _, holes: false);
            var f = new WeatherFields();
            f.Fill(0, Wet(270), t, 7000, P, 0);
            int cell = 100 * W + 200;
            f.At(cell, out var open);
            f.At(cell, 0, out var none);
            f.At(cell, 128, out var half);
            f.At(cell, 255, out var dense);
            Assert.That(open.Wind, Is.GreaterThan(50));
            Assert.That(none.Wind, Is.EqualTo(open.Wind));
