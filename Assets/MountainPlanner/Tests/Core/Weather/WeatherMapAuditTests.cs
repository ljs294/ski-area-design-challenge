        [Test]
        public void TheValleyFloorIsTheLowestCellWithinAKilometre()
        {
            var t = RoughTerrain(out var feet);
            const int r = 125;
            // Brute force, separable (a square window's minimum is the minimum of its rows' minima).
            var rows = new int[W * D];
            for (int j = 0; j < D; j++)
                for (int i = 0; i < W; i++)
                {
                    int m = int.MaxValue;
                    for (int x = Math.Max(0, i - r); x <= Math.Min(W - 1, i + r); x++) { int v = feet[j * W + x]; if (v != int.MinValue && v < m) m = v; }
                    rows[j * W + i] = m;
                }
            for (int j = 0; j < D; j++)
                for (int i = 0; i < W; i++)
                {
                    int c = j * W + i;
                    if (feet[c] == int.MinValue) { Assert.That(t.Hvf[c], Is.EqualTo(WeatherTerrain.NoData)); continue; }
                    int m = int.MaxValue;
                    for (int y = Math.Max(0, j - r); y <= Math.Min(D - 1, j + r); y++) m = Math.Min(m, rows[y * W + i]);
                    int expected = Math.Min(254, (feet[c] - m + 5) / 10);
                    if (t.Hvf[c] != expected) Assert.Fail($"hvf at ({i}, {j}): {t.Hvf[c]}, brute force {expected}");
                }
        }

