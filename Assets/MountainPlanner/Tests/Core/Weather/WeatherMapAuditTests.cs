        [Test]
        public void ATallAreasSummitKeepsItsOwnBin()
        {
            const int w = 96, d = 64;
            var feet = new int[w * d];
            for (int j = 0; j < d; j++) for (int i = 0; i < w; i++) feet[j * w + i] = 2000 + i * 12000 / (w - 1);
            var t = WeatherTerrain.Build(w, d, feet, 0, 0, (0, 0, w, d), 0, Tuning);
            Assert.That(t.BinFeet, Is.GreaterThan(WeatherTerrain.MinBinFeet), "12,000 ft of relief needs coarser bins");
            for (int i = 0; i < w; i++)
                Assert.That(t.BinCentreFeet(t.Bin[i]), Is.EqualTo(feet[i]).Within(t.BinFeet / 2 + 1), $"column {i}");
            var f = new WeatherFields();
            var still = Wet(270, liquid: 0);
            still.Pool = 0;
            f.Fill(0, still, t, 2000, P, 0);
            f.At(w - 1, out var top);
            f.At(0, out var bottom);
            // 12,000 ft at 3.6 °F per 1,000 ft: 43 °F colder on top, to within a bin.
            Assert.That(bottom.Temp - top.Temp, Is.InRange(425, 440));

            Assert.That(RoughTerrain(out _).BinFeet, Is.EqualTo(WeatherTerrain.MinBinFeet), "an ordinary area keeps 10 m bins");
        }

