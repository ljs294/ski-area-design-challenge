        [Test]
        public void TheValleyFloorIsTheLowestCellWithinAKilometre()
        {
            var t = RoughTerrain(out var feet);
            const int r = 125;
            // Brute force, separable (a square window's minimum is the minimum of its rows' minima).
            var rows = new int[W * D];
            for (int j = 0; j < D; j++)
                for (int i = 0; i < W; i++)
                {
                    int m = int.MaxValue;
                    for (int x = Math.Max(0, i - r); x <= Math.Min(W - 1, i + r); x++) { int v = feet[j * W + x]; if (v != int.MinValue && v < m) m = v; }
                    rows[j * W + i] = m;
                }
            for (int j = 0; j < D; j++)
                for (int i = 0; i < W; i++)
                {
                    int c = j * W + i;
                    if (feet[c] == int.MinValue) { Assert.That(t.Hvf[c], Is.EqualTo(WeatherTerrain.NoData)); continue; }
                    int m = int.MaxValue;
                    for (int y = Math.Max(0, j - r); y <= Math.Min(D - 1, j + r); y++) m = Math.Min(m, rows[y * W + i]);
                    int expected = Math.Min(254, (feet[c] - m + 5) / 10);
                    if (t.Hvf[c] != expected) Assert.Fail($"hvf at ({i}, {j}): {t.Hvf[c]}, brute force {expected}");
                }
        }

        [Test]
        public void TheFactorsMeanOverTheBoxIsOneForEveryWind()
        {
            var t = RoughTerrain(out _);   // the box is inside the grid, as in the game (the ring is the grid)
            int cells = t.CoarseWidth * t.CoarseDepth;
            for (int o = 0; o < 8; o++)
            {
                long sum = 0;
                int n = 0, low = int.MaxValue, high = 0;
                for (int j = 0; j < t.CoarseDepth; j++)
                    for (int i = 0; i < t.CoarseWidth; i++)
                    {
                        int cx = i * 64 + 32, cy = j * 64 + 32;
                        if (cx < 40 || cx >= W - 40 || cy < 30 || cy >= D - 30) continue;
                        int v = t.Orographic[o * cells + j * t.CoarseWidth + i];
                        sum += v; n++;
                        low = Math.Min(low, v); high = Math.Max(high, v);
                    }
                Assert.That(n, Is.GreaterThan(4));
                Assert.That((double)sum / n, Is.EqualTo(1000).Within(8), $"octant {o}");
                Assert.That(high, Is.GreaterThan(low), $"octant {o}: the terrain shapes it");
            }
        }

        [Test]
        public void EveryWindRunsAlongTheValleyFloorAndABlendLiesBetweenItsOctants()
        {
            const int w = 400, d = 400;
            var feet = new int[w * d];
            for (int j = 0; j < d; j++) for (int i = 0; i < w; i++) feet[j * w + i] = 6000 + Math.Abs(i - w / 2) * 8;
            var t = WeatherTerrain.Build(w, d, feet, -w * 4000, -d * 4000, (0, 0, w, d), d / 2 * w + 230, Tuning);
            int floor = d / 2 * w + w / 2, slope = d / 2 * w + w / 2 + 160;
            var f = new WeatherFields();
            for (int o = 0; o < 8; o++)
            {
                f.Fill(o, Wet(o * 45, 0), t, 6000, P, 0);
                f.At(floor, out var c);
                int off = Math.Min(c.Direction % 180, 180 - c.Direction % 180);
                Assert.That(off, Is.LessThanOrEqualTo(6), $"a wind from {o * 45}° runs {c.Direction}° on the floor of a north–south valley");
            }
            // Between two octants the slope's wind lies between theirs (speed and direction).
            WeatherCell A(int direction) { f.Fill(9, Wet(direction, 0), t, 6000, P, 0); f.At(slope, out var c); return c; }
            var a = A(225);
            var b = A(270);
            var mid = A(248);
            Assert.That(mid.Wind, Is.InRange(Math.Min(a.Wind, b.Wind), Math.Max(a.Wind, b.Wind)));
            Assert.That(mid.Direction, Is.InRange(Math.Min(a.Direction, b.Direction), Math.Max(a.Direction, b.Direction)));
            // And a storm's own direction, not the hour's wind, picks the precipitation's octants.
            f.Fill(10, Wet(90, 12, stormDirection: 270), t, 6000, P, 0);
            f.At(slope, out var west);
            f.Fill(11, Wet(90, 12, stormDirection: 90), t, 6000, P, 0);
            f.At(slope, out var east);
            Assert.That(west.Liquid, Is.Not.EqualTo(east.Liquid), "the east slope is windward for one storm and lee for the other");
        }

        [Test]
        public void FreezingRainNeedsThePoolAndWarmAirAloft()
        {
            const int w = 400, d = 400;
            var feet = new int[w * d];
            for (int j = 0; j < d; j++) for (int i = 0; i < w; i++) feet[j * w + i] = 6000 + Math.Abs(i - w / 2) * 8;
            var t = WeatherTerrain.Build(w, d, feet, -w * 4000, -d * 4000, (0, 0, w, d), d / 2 * w + 230, Tuning);
            int floor = d / 2 * w + w / 2;
            WeatherCell At(int temp, int dew, int pool)
            {
                var f = new WeatherFields();
                f.Fill(0, new WeatherHour { Temp = temp, Dew = dew, Pool = pool, Liquid = 10, Wind = 100, GustFactor = 1500, StormOrdinal = 0 }, t, 6000, P, 0);
                f.At(floor, out var c);
                return c;
            }
            Assert.That(At(380, 370, 200).FreezingRain, "warm air aloft over a pooled floor");
            Assert.That(At(380, 370, 0).FreezingRain, Is.False, "no pool: plain rain");
            Assert.That(At(380, 370, 0).SnowPermille, Is.EqualTo(0));
            var cold = At(300, 280, 200);
            Assert.That(cold.FreezingRain, Is.False, "cold aloft too: it snows");
            Assert.That(cold.SnowPermille, Is.EqualTo(1000));
            Assert.That(At(380, 370, 40).FreezingRain, Is.False, "a weak pool leaves the floor above freezing");
        }

