        sealed class FakeTime : IRealTime
        {
            public long Microseconds { get; set; }
        }

        static (SimulationHost, FakeTime) Host(bool held)
        {
            var t = new FakeTime();
            var w = new SimWorld(P, SeasonRunner.GoldenDesign(1, false), SimSite.None, 2026);
            return (new SimulationHost(w, t, threaded: false, held: held), t);
        }

        static void Run(SimulationHost h, FakeTime t, int passes = 40)
        {
            for (int k = 0; k < passes; k++) { t.Microseconds += 250_000; h.Service(); }
        }

        [Test]
        public void AHeldHostStepsNothingWhateverIsPressed()
        {
            var (h, t) = Host(held: true);
            Assert.That(h.Latest.Held);
            h.Send(SimCommandKind.Resume);
            Run(h, t);
            Assert.That(h.Latest.Tick, Is.EqualTo(0), "Play");
            h.Send(SimCommandKind.SetSpeed, 4);
            Run(h, t);
            Assert.That(h.Latest.Tick, Is.EqualTo(0), "8×, with seconds of real time behind it");
            h.Send(SimCommandKind.TogglePause);
            h.Send(SimCommandKind.TogglePause);
            h.Send(SimCommandKind.SkipToNextThird);
            Run(h, t);
            var s = h.Latest;
            Assert.That(s.Tick, Is.EqualTo(0), "a skip");
            Assert.That(s.Held);

            h.Send(SimCommandKind.Release);
            Run(h, t);
            s = h.Latest;
            Assert.That(s.Held, Is.False);
            Assert.That(s.Tick, Is.GreaterThan(0), "released: what was asked for runs");
        }

        [Test]
        public void AReleaseKeepsThePlayersPause()
        {
            var (h, t) = Host(held: true);
            Run(h, t);
            h.Send(SimCommandKind.Release);
            Run(h, t);
            var s = h.Latest;
            Assert.That((s.Held, s.Paused, s.Tick), Is.EqualTo((false, true, 0L)), "never played: released into its pause, nothing owed");

            // And a hold in the middle of a run stops it at once, with nothing owed for the wait.
            h.Send(SimCommandKind.SetSpeed, 1);
            Run(h, t, 8);
            h.Send(SimCommandKind.Hold);
            Run(h, t, 2);
            long at = h.Latest.Tick;
            Assert.That(at, Is.GreaterThan(0));
            Run(h, t, 40);
            Assert.That(h.Latest.Tick, Is.EqualTo(at));
            h.Send(SimCommandKind.Release);
            t.Microseconds += 100;
            h.Service();
            Assert.That(h.Latest.Tick, Is.LessThanOrEqualTo(at + 1), "the ten held seconds aren't run as a backlog");
        }

