        [Test]
        public void TwoLiftsAtOneHeightGustByTheirOwnGround()
        {
            const int w = 400, d = 400;
            var feet = new int[w * d];
            for (int j = 0; j < d; j++) for (int i = 0; i < w; i++) feet[j * w + i] = 6000 + Math.Abs(i - w / 2) * 8;
            var t = WeatherTerrain.Build(w, d, feet, -w * 4000, -d * 4000, (0, 0, w, d), d / 2 * w + 230, Tuning);
            (int X, int Y) Mm(int i) => (t.OriginXMm + (i * 8 + 4) * 1000, t.OriginYMm + (200 * 8 + 4) * 1000);
            LiftInput Lift(ulong id, int i) =>
                new LiftInput(id, true, LiftSchedule.Daily, null, LiftKind.DetachableChair, 4, 6000, 360_000, topFeet: 7000, topMm: Mm(i));
            var design = new SimDesign(1, 1, 77, DayHours.Default, new[] { Lift(1, 200), Lift(2, 360) }, 1);
            var world = new SimWorld(P, design, SimSite.None, 2026, weather: SimWeatherTests.Golden());
            world.ApplyNow(SimCommand.Of(SimCommandKind.SetWeatherTerrain, 0, t));
            var s = new SimSnapshot(P);
            int hours = 0, more = 0;
            long last = world.HourIndex;
            while (world.FaceMs < 6 * SimWorld.DayMs)
            {
                world.Step(P.IdleTickFactor);
                if (world.HourIndex == last) continue;
                last = world.HourIndex;
                world.Write(s);
                for (int k = 0; k < 2; k++)
                {
                    s.WeatherFields.At(t.CellAt(Mm(k == 0 ? 200 : 360).X, Mm(0).Y), out var c);
                    Assert.That(s.LiftGustTenths[k], Is.EqualTo(c.Gust), $"lift {k + 1}'s gust is its top station's cell");
                }
                if (s.LiftGustTenths[0] + s.LiftGustTenths[1] == 0) continue;
                hours++;
                if (s.LiftGustTenths[1] > s.LiftGustTenths[0]) more++;
            }
            Assert.That(hours, Is.GreaterThan(80));
            Assert.That(more, Is.EqualTo(hours), "the same height, so only the ground can tell them apart");
        }

