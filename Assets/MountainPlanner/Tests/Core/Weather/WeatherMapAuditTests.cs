        /// <summary>Rough hills on a grid that is no multiple of 64 or 12, with a hole and a strip without heights.</summary>
        static int[] Rough(int w, int d, bool holes)
        {
            var feet = new int[w * d];
            for (int j = 0; j < d; j++)
                for (int i = 0; i < w; i++)
                {
                    double v = 7000 + 1400 * Math.Sin(i * 0.013) * Math.Cos(j * 0.011) + 500 * Math.Sin(i * 0.05 + j * 0.031) + 60 * Math.Sin(i * 0.37) * Math.Sin(j * 0.29);
                    bool hole = holes && ((i > 120 && i < 150 && j > 60 && j < 100) || i < 9 || (j == 170 && i > 200));
                    feet[j * w + i] = hole ? int.MinValue : (int)v;
                }
            return feet;
        }

        const int W = 301, D = 227;

        static WeatherTerrain RoughTerrain(out int[] feet, bool holes = true)
        {
            feet = Rough(W, D, holes);
            return WeatherTerrain.Build(W, D, feet, -W * 4000, -D * 4000, (40, 30, W - 40, D - 30), D / 2 * W + W / 2, Tuning);
        }

        static WeatherHour Wet(int direction, int liquid = 12, int stormDirection = -1)
        {
            return new WeatherHour
            {
                Temp = 290, Dew = 270, Lapse = 36, DewLapse = 20, Pool = 40, Liquid = liquid, PrecipGradient = 8,
                Wind = 180, GustFactor = 1600, Direction = direction, StormOrdinal = 3, StormDirection = stormDirection < 0 ? direction : stormDirection,
            };
        }

