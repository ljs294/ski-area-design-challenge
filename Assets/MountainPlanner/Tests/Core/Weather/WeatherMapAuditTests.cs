        [Test]
        public void TheBatchReadIsThePointReadAndACopyIsItsSource()
        {
            var t = RoughTerrain(out _);
            var canopy = new byte[W * D];
            for (int k = 0; k < canopy.Length; k++) canopy[k] = (byte)(k * 37 % 256);
            var f = new WeatherFields();
            f.Fill(5, Wet(200, 12, stormDirection: 290), t, 7000, P, 311);
            var copy = new WeatherFields();
            copy.Fill(1, Wet(10), RoughTerrain(out _, holes: false), 6000, P, 0);   // other inputs first: the copy must replace them
            copy.CopyFrom(f);
            Assert.That((copy.Hour, copy.Terrain), Is.EqualTo((f.Hour, f.Terrain)));

            var band = new WeatherCell[50 * W];
            int known = 0, wet = 0;
            for (int y0 = 0; y0 < D; y0 += 50)
            {
                int rows = Math.Min(50, D - y0);
                f.ReadRows(y0, y0 + rows, band, null, canopy);
                for (int j = 0; j < rows; j++)
                    for (int i = 0; i < W; i++)
                    {
                        int cell = (y0 + j) * W + i;
                        f.At(cell, canopy[cell], out var a);
                        copy.At(cell, canopy[cell], out var b);
                        if (!a.Equals(band[j * W + i]) || !a.Equals(b)) Assert.Fail($"cell ({i}, {y0 + j}) differs between the reads");
                        if (a.Known) known++;
                        if (a.Liquid > 0) wet++;
                    }
            }
            Assert.That(known, Is.InRange(W * D * 8 / 10, W * D - 1000), "the holes are unknown, the rest known");
            Assert.That(wet, Is.GreaterThan(known * 9 / 10));
            f.At(80 * W + 135, out var hole);
            Assert.That(hole.Known, Is.False);
            f.At(-1, out hole);
            Assert.That(hole.Known, Is.False);
            f.At(W * D, out hole);
            Assert.That(hole.Known, Is.False);
        }

