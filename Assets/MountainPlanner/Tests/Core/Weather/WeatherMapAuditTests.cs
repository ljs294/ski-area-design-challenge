        [Test]
        public void TheWetBulbHoldsThroughTheSnowLineOffTheTablesNodes()
        {
            double worst = 0;
            foreach (double hPa in new[] { 1013.25, 812.0, 697.0 })
                for (int temp = 283; temp <= 383; temp += 7)          // 28.3 … 38.3 °F, between whole degrees
                    for (int rh = 605; rh <= 985; rh += 38)           // between whole per cents
                    {
                        double reference = Psychro(temp / 10.0, rh / 10.0, hPa);
                        double gap = WeatherAir.WetBulb(temp, rh) / 10.0 - reference;
                        worst = Math.Max(worst, Math.Abs(gap));
                        Assert.That(gap, Is.InRange(-1.5, 1.5), $"{temp / 10.0} °F, {rh / 10.0} %, {hPa} hPa");
                    }
            TestContext.Progress.WriteLine($"28–38 °F, RH 60–99 %, sea level to 10,000 ft: the worst gap from the equation {worst:F2} °F");
        }

        static double Psychro(double tempF, double rhPercent, double hPa)
        {
            double t = Psychrometrics.FToC(tempF);
            static double Es(double c) => 6.112 * Math.Exp(17.67 * c / (c + 243.5));
            double e = rhPercent / 100 * Es(t), lo = t - 40, hi = t;
            for (int k = 0; k < 80; k++)
            {
                double tw = (lo + hi) / 2;
                if (Es(tw) - 6.60e-4 * (1 + 0.00115 * tw) * hPa * (t - tw) - e > 0) hi = tw; else lo = tw;
            }
            return Psychrometrics.CToF((lo + hi) / 2);
        }

