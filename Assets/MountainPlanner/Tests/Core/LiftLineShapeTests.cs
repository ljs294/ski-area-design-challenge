        static LiftBuild.Result Build(string catalogId, double[] profile, double length) =>
            LiftBuild.Build(LiftType.Of(catalogId), new EditedHeights(new Sampled(profile), Lattice, TerrainEdits.Empty),
                            West + 100, North - 2000, West + 100, North - 2000 + length, TowerStance.Leaned);

        static string Describe(LiftBuild.Result b) =>
            string.Join(", ", b.Towers.Select((t, i) => $"{t.AlongMm / 304.8:F0}/{t.HeightMm / 304.8:F0} {b.Rope.Towers[i].Head}"));

        /// <summary>Spans shorter than 100 ft: the breakovers bunched (a few before a terminal or after a rise are fine, E3).</summary>
        static int Bunched(LiftBuild.Result b) =>
            b.Towers.Zip(b.Towers.Skip(1), (x, y) => y.AlongMm - x.AlongMm).Count(d => d < DesignUnits.FeetToMm(100));

        static void AssertNatural(LiftBuild.Result b, string what, int maxTowers, int maxBunched)
        {
            TestContext.Progress.WriteLine($"{what}: {b.Towers.Count} towers: {Describe(b)}; exit {b.Rope.BottomExitEmpty * 180 / Math.PI:F2}°, top {b.Rope.TopEntryEmpty * 180 / Math.PI:F2}°");
            Assert.That(b.Rope.Towers.All(t => t.Head != LiftRope.Head.TooSharp), Is.True, $"{what}: no head too sharp (TW-06), the station towers' too (E2, E4)");
            Assert.That(b.Towers.Max(t => t.HeightMm), Is.LessThanOrEqualTo(DesignUnits.FeetToMm(100)), $"{what}: TW-02's 100 ft");
            Assert.That(b.Towers.Count, Is.LessThanOrEqualTo(maxTowers), $"{what}: the fewest towers");
            Assert.That(Bunched(b), Is.LessThanOrEqualTo(maxBunched), $"{what}: breakovers grouped, not a run 50 ft apart");
        }

        [Test]
        public void E3_TheUpperChair6()
        {
            // Was 19 towers, ten of them 50–75 ft apart in the top 550 ft on steel rising to 90 ft, and two heads too sharp.
            var b = Build(LiftCatalogIds.SesselliftD6, UpperChair6, UpperLength);
            AssertNatural(b, "D6, upper Chair 6", 14, 3);
            // LT43: a detachable's ends are level at the terminal's rope height, empty.
            Assert.That(Math.Abs(b.Rope.BottomExitEmpty) * 180 / Math.PI, Is.LessThan(0.1), "level out of the bottom terminal (E4)");
            Assert.That(Math.Abs(b.Rope.TopEntryEmpty) * 180 / Math.PI, Is.LessThan(0.1), "level into the top terminal (E2)");
            AssertNatural(Build(LiftCatalogIds.SesselliftFgq4, UpperChair6, UpperLength), "FGQ-4, upper Chair 6", 13, 3);
        }

        [Test]
        public void E3_TheLongChair6()
        {
            // Was 35 towers with a too-sharp first tower and three tight pairs.
            var b = Build(LiftCatalogIds.SesselliftD6, LongChair6, LongLength);
            AssertNatural(b, "D6, long Chair 6", 30, 2);
            Assert.That(Math.Abs(b.Rope.BottomExitEmpty) * 180 / Math.PI, Is.LessThan(0.1), "level out of the bottom terminal (E4)");
            Assert.That(Math.Abs(b.Rope.TopEntryEmpty) * 180 / Math.PI, Is.LessThan(0.1), "level into the top terminal (E2)");
        }
